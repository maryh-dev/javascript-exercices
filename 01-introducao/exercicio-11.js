// Explique a diferença entre os operadores == e ===. 
// Apresente um exemplo de cada um.

console.log(5 == "5"); // true, pois o == compara apenas o valor e permite conversão de tipo.

console.log(5 === "5"); // false, pois o === compara o valor e também o tipo de dado.

// O == faz uma comparação mais flexível, podendo converter os tipos. 
// O === faz uma comparação estrita, verificando o valor e o tipo.
